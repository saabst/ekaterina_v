MIN_VALID_BYTES = 1000
CONCURRENCY = 5
RETRIES = 3


async def synthesize(sem: asyncio.Semaphore, clip_id: str, tone: str, text: str, force: bool) -> str:
    out_path = OUT_DIR / f"{clip_id}_{tone}.mp3"
    if not force and out_path.exists() and out_path.stat().st_size > MIN_VALID_BYTES:
        return f"skip  {out_path.name}"

    params = TONE_PARAMS[tone]
    async with sem:
        last_error: Exception | None = None
        for attempt in range(1, RETRIES + 1):
            try:
                communicate = edge_tts.Communicate(
                    text,
                    VOICE,
                    rate=params["rate"],
                    pitch=params["pitch"],
                )
                await communicate.save(str(out_path))
                if out_path.stat().st_size > MIN_VALID_BYTES:
                    return f"ok    {out_path.name}"
                raise RuntimeError("generated file is too small")
            except Exception as error:  # network hiccups are retried
                last_error = error
                await asyncio.sleep(1.0 * attempt)
        raise RuntimeError(f"failed {out_path.name}: {last_error}")


async def main(force: bool) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    sem = asyncio.Semaphore(CONCURRENCY)
    tasks = [
        synthesize(sem, clip_id, tone, text, force)
        for clip_id, pair in CLIPS.items()
        for tone, text in pair.items()
    ]
    results = await asyncio.gather(*tasks)
    created = sum(1 for r in results if r.startswith("ok"))
    skipped = sum(1 for r in results if r.startswith("skip"))
    print(f"Готово: создано {created}, пропущено {skipped}, всего {len(results)} → {OUT_DIR}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Синтез озвучки Екатерины II")
    parser.add_argument("--force", action="store_true", help="перегенерировать все файлы")
    args = parser.parse_args()
    asyncio.run(main(args.force))
